def parse(block):
    players = []
    for line in block.strip().splitlines():
        line = line.strip()
        if not line or "|" not in line:
            continue
        num, name = line.split("|", 1)
        num = num.strip()
        if not re.fullmatch(r"\d{1,3}", num):
            continue
        players.append({"number": int(num), "name": name.strip(), "position": ""})
    players.sort(key=lambda p: p["number"])
    return players

clubs = []
for name, short, color, block in CLUBS:
    clubs.append({"name": name, "short": short, "color": color,
                  "source": "ileague.id", "players": parse(block)})

out = Path(__file__).resolve().parents[1] / "data" / "clubs.json"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps({
    "season": SEASON,
    "competition": "Liga Nusantara 2026-27",
    "note": "Rosters scraped from ileague.id (2026-11-18). ileague shows no positions or kit colours: position is blank (mark the GK in the Tagger's Pick XI), colours are placeholders — confirm from the broadcast. Rebuild with scripts/build_clubs_json.py.",
    "clubs": clubs,
}, ensure_ascii=False, indent=2))
total = sum(len(c["players"]) for c in clubs)
print(f"Wrote {out} — {len(clubs)} clubs, {total} players.")
